IDENT_EXTRA = (
    (0x24, 0x24),
    (0x30, 0x39), (0x300, 0x36f), (0x1dc0, 0x1dff), (0x20d0, 0x20ff),
    (0xfe20, 0xfe2f),
)

def in_range(character, ranges):
    value = ord(character)
    return any(lo <= value <= hi for lo, hi in ranges)


def is_ident1(character):
    return in_range(character, IDENT_START)


def is_ident2(character):
    return is_ident1(character) or in_range(character, IDENT_EXTRA)
